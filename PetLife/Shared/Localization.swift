    static func text(_ value: String) -> String {
        guard isEnglish else { return value }
        if let exact = english[value] { return exact }
        for (expression, translation) in templates {
            let range = NSRange(value.startIndex..., in: value)
            guard let match = expression.firstMatch(in: value, range: range) else { continue }
            var output = translation
            for index in 1..<match.numberOfRanges {
                guard let part = Range(match.range(at: index), in: value) else { continue }
                let capture = String(value[part])
                output = output.replacingOccurrences(of: "{\(index - 1)}", with: capture)
            }
            return output
        }
        return value
    }
    private static let templates: [(NSRegularExpression, String)] = english.compactMap { key, value in
        guard key.contains("{0}") else { return nil }
        let segments = key.components(separatedBy: try! NSRegularExpression(pattern: #"\{\d+\}"#))
        let pattern = "^" + segments.map(NSRegularExpression.escapedPattern(for:)).joined(separator: "(.*?)") + "$"
        return (try! NSRegularExpression(pattern: pattern, options: [.dotMatchesLineSeparators]), value)
    }
